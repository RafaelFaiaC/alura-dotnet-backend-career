/*Calculating the Area of a Rectangle

You have been hired by a civil construction company. The company is expanding its projects and needs a system to calculate the area of rectangular plots of land. To do this, use the formula:
area = width * length

For this activity, you must create a program that:
- Declares two variables for the width and length, respectively.
- Applies the mentioned formula to calculate the plot's area.
- Displays the calculation result.

Example Input:
double width = 10.5;
double length = 20.3;

Expected Output:
The area of the land is: 213.15 square meters.
*/

double width = 10.5;
double length = 20.3;
double area = width * length;

Console.WriteLine($"The area of the land is: {area} square meters");